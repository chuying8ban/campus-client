    fun current(ctx: Context): String {
        val i = prefs(ctx).getInt(K_CUR, -1)
        return if (i in all.indices) all[i] else all.first()
    }

    /** 进 App 调一次：队列取下一条，尽量不与上一条重复。 */
    fun advance(ctx: Context): String {
        val sp = prefs(ctx)
        val cur = sp.getInt(K_CUR, -1)
        val queue = sp.getString(K_QUEUE, "").orEmpty()
            .split(',')
            .mapNotNull { it.trim().toIntOrNull() }
            .filter { it in all.indices }
            .toMutableList()

        val next = if (queue.isEmpty()) {
            // 新一轮：洗牌，并保证第一张不是刚刚那张
            val fresh = all.indices.shuffled().toMutableList()
            if (fresh.size > 1 && fresh.first() == cur) {
                val j = fresh.indexOfFirst { it != cur }
                if (j > 0) { val t = fresh[0]; fresh[0] = fresh[j]; fresh[j] = t }
            }
            val pick = fresh.removeAt(0)
            sp.edit().putString(K_QUEUE, fresh.joinToString(",")).putInt(K_CUR, pick).apply()
            pick
        } else {
            val pick = queue.removeAt(0)
            sp.edit().putString(K_QUEUE, queue.joinToString(",")).putInt(K_CUR, pick).apply()
            pick
        }
        return all[next]
    }

    private fun prefs(ctx: Context) =
        ctx.applicationContext.getSharedPreferences("campus_soup", Context.MODE_PRIVATE)
